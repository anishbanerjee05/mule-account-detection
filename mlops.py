DB_PATH = 'mule_detection.db'

# ── Database setup ────────────────────────────────────────────────────────────
def init_database():
    conn = sqlite3.connect(DB_PATH)
    c    = conn.cursor()

    # Alerts table — every alert generated by the consumer
    c.execute('''
        CREATE TABLE IF NOT EXISTS alerts (
            id              INTEGER PRIMARY KEY AUTOINCREMENT,
            account_id      TEXT NOT NULL,
            probability     REAL NOT NULL,
            tier            TEXT NOT NULL,
            amount          REAL,
            payment_format  TEXT,
            total_txn       INTEGER,
            fan_out         INTEGER,
            cross_bank      INTEGER,
            has_gnn_embed   INTEGER,
            is_laundering   INTEGER,
            timestamp       TEXT,
            created_at      TEXT DEFAULT (datetime('now'))
        )
    ''')

    # Analyst decisions table — human feedback loop
    c.execute('''
        CREATE TABLE IF NOT EXISTS analyst_decisions (
            id              INTEGER PRIMARY KEY AUTOINCREMENT,
            alert_id        INTEGER,
            account_id      TEXT NOT NULL,
            decision        TEXT NOT NULL,  -- 'true_positive' or 'false_positive'
            reason_code     TEXT,
            analyst_id      TEXT DEFAULT 'system',
            decided_at      TEXT DEFAULT (datetime('now')),
            FOREIGN KEY (alert_id) REFERENCES alerts(id)
        )
    ''')

    # Model registry — every model version trained
    c.execute('''
        CREATE TABLE IF NOT EXISTS model_registry (
            id                  INTEGER PRIMARY KEY AUTOINCREMENT,
            model_version       TEXT NOT NULL,
            training_date       TEXT NOT NULL,
            training_data_from  TEXT,
            training_data_to    TEXT,
            auc_roc             REAL,
            avg_precision       REAL,
            f1_optimal          REAL,
            optimal_threshold   REAL,
            n_training_samples  INTEGER,
            n_fraud_samples     INTEGER,
            feature_count       INTEGER,
            is_active           INTEGER DEFAULT 0,
            notes               TEXT,
            created_at          TEXT DEFAULT (datetime('now'))
        )
    ''')

    # Drift log — hourly feature distribution monitoring
    c.execute('''
        CREATE TABLE IF NOT EXISTS drift_log (
            id              INTEGER PRIMARY KEY AUTOINCREMENT,
            feature_name    TEXT NOT NULL,
            psi_score       REAL,
            drift_detected  INTEGER DEFAULT 0,
            baseline_mean   REAL,
            current_mean    REAL,
            logged_at       TEXT DEFAULT (datetime('now'))
        )
    ''')

    conn.commit()
    conn.close()
    print("Database initialised: mule_detection.db")
    print("Tables: alerts, analyst_decisions, model_registry, drift_log")

# ── Alert ingestion ───────────────────────────────────────────────────────────
def ingest_alerts_from_redis():
    """Pull alerts from Redis and store in SQLite."""
    r    = redis.Redis(host='localhost', port=6379, decode_responses=True)
    raw  = r.lrange('alerts', 0, -1)
    conn = sqlite3.connect(DB_PATH)
    c    = conn.cursor()

    ingested = 0
    for item in raw:
        try:
            alert = json.loads(item)
            # Check if already ingested
            c.execute('SELECT id FROM alerts WHERE account_id=? AND timestamp=?',
                      (alert.get('account_id'), alert.get('timestamp')))
            if c.fetchone():
                continue

            c.execute('''
                INSERT INTO alerts
                (account_id, probability, tier, amount, payment_format,
                 total_txn, fan_out, cross_bank, has_gnn_embed,
                 is_laundering, timestamp)
                VALUES (?,?,?,?,?,?,?,?,?,?,?)
            ''', (
                alert.get('account_id'),
                alert.get('probability', 0),
                alert.get('tier', 'UNKNOWN'),
                alert.get('amount', 0),
                alert.get('payment_format', 'unknown'),
                alert.get('total_txn', 0),
                alert.get('fan_out', 0),
                alert.get('cross_bank', 0),
                1 if alert.get('has_gnn_embed') else 0,
                alert.get('is_laundering', 0),
                alert.get('timestamp', '')
            ))
            ingested += 1
        except Exception as e:
            print(f"Error ingesting alert: {e}")

    conn.commit()
    conn.close()
    print(f"Ingested {ingested} new alerts from Redis to SQLite")
    return ingested

# ── Analyst decision recording ────────────────────────────────────────────────
def record_decision(account_id: str, decision: str,
                    reason_code: str = None, analyst_id: str = 'system'):
    """
    Record an analyst decision for an account.
    decision: 'true_positive' or 'false_positive'
    reason_code: 'confirmed_mule', 'legitimate_business', 'insufficient_evidence', etc.
    """
    conn = sqlite3.connect(DB_PATH)
    c    = conn.cursor()

    # Find the most recent alert for this account
    c.execute('SELECT id FROM alerts WHERE account_id=? ORDER BY created_at DESC LIMIT 1',
              (account_id,))
    row = c.fetchone()
    alert_id = row[0] if row else None

    c.execute('''
        INSERT INTO analyst_decisions
        (alert_id, account_id, decision, reason_code, analyst_id)
        VALUES (?,?,?,?,?)
    ''', (alert_id, account_id, decision, reason_code, analyst_id))

    conn.commit()
    conn.close()
    print(f"Decision recorded: {account_id} → {decision} ({reason_code})")

# ── Drift monitor ─────────────────────────────────────────────────────────────
def run_drift_monitor():
    """
    Computes Population Stability Index (PSI) on alert features.
    PSI > 0.25 indicates significant drift — triggers retraining.
    """
    conn = sqlite3.connect(DB_PATH)
    df   = pd.read_sql('SELECT * FROM alerts ORDER BY created_at DESC LIMIT 10000', conn)
    conn.close()

    if len(df) < 100:
        print("Insufficient data for drift monitoring (need 100+ alerts)")
        return False

    # Split into baseline (older half) and current (newer half)
    mid      = len(df) // 2
    baseline = df.iloc[mid:]
    current  = df.iloc[:mid]

    features_to_monitor = ['probability', 'fan_out', 'cross_bank', 'total_txn']
    drift_detected      = False

    print("\n=== DRIFT MONITOR ===")
    print(f"{'Feature':<20} {'Baseline Mean':>14} {'Current Mean':>14} {'PSI':>8} {'Status':>10}")
    print("-" * 70)

    conn = sqlite3.connect(DB_PATH)
    c    = conn.cursor()

    for feat in features_to_monitor:
        try:
            base_vals = baseline[feat].dropna().values
            curr_vals = current[feat].dropna().values

            if len(base_vals) == 0 or len(curr_vals) == 0:
                continue

            # Compute PSI
            base_mean = float(np.mean(base_vals))
            curr_mean = float(np.mean(curr_vals))

            # Bin the data into 10 buckets
            bins = np.percentile(base_vals, np.linspace(0, 100, 11))
            bins = np.unique(bins)
            if len(bins) < 2:
                continue

            base_pct = np.histogram(base_vals, bins=bins)[0] / len(base_vals)
            curr_pct = np.histogram(curr_vals, bins=bins)[0] / len(curr_vals)

            # Add small epsilon to avoid log(0)
            base_pct = np.where(base_pct == 0, 1e-6, base_pct)
            curr_pct = np.where(curr_pct == 0, 1e-6, curr_pct)

            psi = float(np.sum((curr_pct - base_pct) * np.log(curr_pct / base_pct)))

            status = "DRIFT" if psi > 0.25 else "STABLE"
            if psi > 0.25:
                drift_detected = True

            print(f"{feat:<20} {base_mean:>14.4f} {curr_mean:>14.4f} {psi:>8.4f} {status:>10}")

            # Log to database
            c.execute('''
                INSERT INTO drift_log (feature_name, psi_score, drift_detected,
                                       baseline_mean, current_mean)
                VALUES (?,?,?,?,?)
            ''', (feat, psi, 1 if psi > 0.25 else 0, base_mean, curr_mean))

        except Exception as e:
            print(f"Error computing drift for {feat}: {e}")

    conn.commit()
    conn.close()

    if drift_detected:
        print("\nDRIFT DETECTED — retraining recommended")
    else:
        print("\nAll features stable")

    return drift_detected

# ── Retraining pipeline ───────────────────────────────────────────────────────
def retrain_hybrid_model():
    """
    Retrains the hybrid XGBoost model using:
    1. Original IBM AML feature matrix
    2. Analyst-confirmed labels (5x weight)
    3. Current GNN embeddings from Redis
    """
    print("\n=== RETRAINING HYBRID MODEL ===")
    print(f"Started: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")

    # Load base feature matrix
    print("Loading IBM AML feature matrix...")
    ibm_feat = pd.read_csv('ibm_feature_matrix.csv')
    ibm_feat['Account'] = ibm_feat['Account'].astype(str)

    feat_cols = [
        'velocity_ratio','balance_retention_rate','fan_out_degree',
        'cross_bank_degree','round_amount_ratio','structuring_score',
        'amount_variance_score','session_burst_score','dormancy_ratio',
        'total_transactions','avg_amount','max_amount'
    ]

    X_base = ibm_feat[feat_cols].fillna(0).values
    y_base = ibm_feat['is_laundering'].fillna(0).values.astype(int)
    accounts = ibm_feat['Account'].values
    weights  = np.ones(len(X_base))

    # Load analyst decisions and add with 5x weight
    conn = sqlite3.connect(DB_PATH)
    decisions = pd.read_sql('''
        SELECT account_id, decision FROM analyst_decisions
        WHERE decided_at > datetime('now', '-7 days')
    ''', conn)
    conn.close()

    if len(decisions) > 0:
        print(f"Analyst decisions found: {len(decisions)}")
        tp_accounts = set(decisions[decisions['decision']=='true_positive']['account_id'])
        fp_accounts = set(decisions[decisions['decision']=='false_positive']['account_id'])

        for i, acc in enumerate(accounts):
            if acc in tp_accounts:
                weights[i] = 5.0   # 5x weight for confirmed fraud
            elif acc in fp_accounts:
                weights[i] = 0.2   # Reduce weight for confirmed legitimate
    else:
        print("No analyst decisions found — using base training data only")

    # Retrieve GNN embeddings from Redis
    print("Retrieving GNN embeddings from Redis...")
    r = redis.Redis(host='localhost', port=6379, decode_responses=True)
    embeddings = []
    found = 0

    batch_size = 5000
    for i in range(0, len(accounts), batch_size):
        batch = accounts[i:i+batch_size]
        pipe  = r.pipeline()
        for acc in batch:
            pipe.get(f"embed:{acc}")
        results = pipe.execute()
        for res in results:
            if res:
                embeddings.append(json.loads(res))
                found += 1
            else:
                embeddings.append([0.0] * 64)

    embeddings = np.array(embeddings)
    print(f"Embeddings: {found:,} found, {len(accounts)-found:,} zero-filled")

    # Combine features
    X_hybrid = np.concatenate([X_base, embeddings], axis=1)
    print(f"Hybrid feature matrix: {X_hybrid.shape}")

    # Train/test split
    X_train, X_test, y_train, y_test, w_train, _ = train_test_split(
        X_hybrid, y_base, weights,
        test_size=0.20, random_state=42, stratify=y_base
    )

    # Scale
    scaler_new = StandardScaler()
    X_train_sc = scaler_new.fit_transform(X_train)
    X_test_sc  = scaler_new.transform(X_test)

    # Train
    print("Training hybrid XGBoost...")
    model_new = xgb.XGBClassifier(
        n_estimators=300,
        learning_rate=0.1,
        max_depth=8,
        scale_pos_weight=5,
        min_child_weight=5,
        subsample=0.8,
        colsample_bytree=0.8,
        gamma=0.1,
        reg_alpha=0.1,
        reg_lambda=1.0,
        eval_metric='aucpr',
        random_state=42,
        n_jobs=-1,
        verbosity=0
    )
    model_new.fit(X_train_sc, y_train, sample_weight=w_train, verbose=False)

    # Evaluate
    y_prob = model_new.predict_proba(X_test_sc)[:,1]
    y_pred = model_new.predict(X_test_sc)

    auc = roc_auc_score(y_test, y_prob)
    ap  = average_precision_score(y_test, y_prob)
    f1  = f1_score(y_test, y_pred)

    precisions, recalls, thresholds = precision_recall_curve(y_test, y_prob)
    f1_scores   = 2*(precisions*recalls)/(precisions+recalls+1e-9)
    best_thresh = float(thresholds[np.argmax(f1_scores)])
    best_f1     = float(f1_scores[np.argmax(f1_scores)])

    print(f"\n=== NEW MODEL RESULTS ===")
    print(f"AUC-ROC:           {auc:.4f}")
    print(f"Average Precision: {ap:.4f}")
    print(f"F1 optimal:        {best_f1:.4f}")
    print(f"Optimal threshold: {best_thresh:.4f}")

    # Load current model metrics for comparison
    with open('hybrid_model_config.json', 'r') as f:
        current_config = json.load(f)

    current_auc = current_config['auc_roc']
    improvement = auc - current_auc

    print(f"\nCurrent AUC-ROC:   {current_auc:.4f}")
    print(f"New AUC-ROC:       {auc:.4f}")
    print(f"Improvement:       {improvement:+.4f}")

    # Save to model registry
    conn = sqlite3.connect(DB_PATH)
    c    = conn.cursor()
    version = f"xgb_hybrid_v{datetime.now().strftime('%Y%m%d_%H%M')}"
    c.execute('''
        INSERT INTO model_registry
        (model_version, training_date, auc_roc, avg_precision,
         f1_optimal, optimal_threshold, n_training_samples,
         n_fraud_samples, feature_count, notes)
        VALUES (?,?,?,?,?,?,?,?,?,?)
    ''', (
        version,
        datetime.now().isoformat(),
        float(auc), float(ap), best_f1, best_thresh,
        len(X_train), int(y_train.sum()),
        X_hybrid.shape[1],
        f"Improvement over previous: {improvement:+.4f}"
    ))
    conn.commit()
    conn.close()

    # Promote if better by 1%
    if improvement >= 0.01:
        print(f"\nModel improved by {improvement:.4f} — promoting to production")
        with open('xgb_hybrid_model.pkl', 'wb') as f:
            pickle.dump(model_new, f)
        with open('scaler_hybrid.pkl', 'wb') as f:
            pickle.dump(scaler_new, f)

        new_config = {
            'optimal_threshold':       best_thresh,
            'feature_cols_behavioral': feat_cols,
            'n_behavioral_features':   12,
            'n_gnn_embedding_dims':    64,
            'n_total_features':        76,
            'model_version':           version,
            'auc_roc':                 float(auc),
            'avg_precision':           float(ap),
            'f1_optimal':              best_f1
        }
        with open('hybrid_model_config.json', 'w') as f:
            json.dump(new_config, f, indent=2)
        print("New model promoted to production")
        return True
    else:
        print(f"\nImprovement {improvement:+.4f} below threshold (0.01) — keeping current model")
        return False

